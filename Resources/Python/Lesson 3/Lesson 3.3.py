#przykladowe liczby
x = 7 
y = 4
 
#dodawanie
print("Wynik dodawnia: ", x+y)
 
#odejmowanie
print("Odejmowanie: ", x-y)
 
#mnożenie
print("Mnożenie: ", x*y)
 
#dzielenie
print("Dzielenie: ", x/y)
 
#poniższe operacje działają dla int i float
print("Dzielenie bez reszty (całkowite): ", x//y) #iloraz jest zaokrąglany w dół, np. -7 // 4 daje -2
print("Reszta z dzielenia: ", x%y) 
 
#potęgowanie
print("Wynik potęgowania liczb: ",x**y)
